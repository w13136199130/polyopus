"""Extract the error catalog from docs/29 into code + i18n catalogs.

M1 pre-work. `docs/29 §2` is the single source of truth.

Usage:
    python tools/extract_errors.py --check
    python tools/extract_errors.py --emit
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "29-API与错误码总表.md"
CODES = ROOT / "src" / "polyopus" / "platform" / "errors" / "codes.py"
LOCALES = ROOT / "src" / "polyopus" / "platform" / "i18n" / "locales"

CODE_RE = re.compile(r"^`([A-Z][A-Z0-9_]+)`$")
HTTP_RE = re.compile(r"^(\d{3})(?:/.*)?$")


class ExtractError(RuntimeError):
    pass


def parse(text: str) -> list[tuple[str, int, str]]:
    out: list[tuple[str, int, str]] = []
    seen: set[str] = set()
    for line in text.splitlines():
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3:
            continue
        m = CODE_RE.match(cells[0])
        h = HTTP_RE.match(cells[1])
        if not m or not h:
            continue
        code = m.group(1)
        if code in seen:
            raise ExtractError(f"duplicate code {code}")
        seen.add(code)
        out.append((code, int(h.group(1)), cells[2]))
    if len(out) < 100:
        raise ExtractError(f"only {len(out)} codes parsed; format changed?")
    return out


def render_codes(codes: list[tuple[str, int, str]]) -> str:
    lines = [
        '"""Stable error codes. GENERATED by tools/extract_errors.py --emit."""',
        "",
        "from __future__ import annotations",
        "",
        "ERROR_CODES: dict[str, int] = {",
    ]
    for code, status, _ in codes:
        lines.append(f'    "{code}": {status},')
    lines += [
        "}",
        "",
        "HTTP_OVERRIDES: dict[str, int] = {}",
        "",
    ]
    return "\n".join(lines)


def _humanize(code: str) -> str:
    return code.replace("_", " ").capitalize()


def render_locale(codes: list[tuple[str, int, str]], locale: str) -> str:
    data = {
        f"error.{code}": (desc if locale == "zh-CN" else _humanize(code))
        for code, _, desc in codes
    }
    return json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def emit(codes: list[tuple[str, int, str]]) -> None:
    CODES.parent.mkdir(parents=True, exist_ok=True)
    CODES.write_text(render_codes(codes), encoding="utf-8", newline="\n")
    LOCALES.mkdir(parents=True, exist_ok=True)
    for locale in ("en", "zh-CN"):
        path = LOCALES / f"error.{locale}.json"
        path.write_text(render_locale(codes, locale), encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)} ({len(codes)} keys)")


def check(codes: list[tuple[str, int, str]]) -> list[str]:
    problems: list[str] = []
    expected = render_codes(codes)
    if not CODES.is_file():
        problems.append("codes.py missing; run --emit")
    elif CODES.read_text(encoding="utf-8").replace("\r\n", "\n") != expected:
        problems.append("codes.py out of sync; run --emit")

    for locale in ("en", "zh-CN"):
        path = LOCALES / f"error.{locale}.json"
        want = render_locale(codes, locale)
        if not path.is_file():
            problems.append(f"{path.name} missing; run --emit")
        elif path.read_text(encoding="utf-8").replace("\r\n", "\n") != want:
            problems.append(f"{path.name} out of sync; run --emit")

    en = json.loads((LOCALES / "error.en.json").read_text(encoding="utf-8")) if (
        LOCALES / "error.en.json"
    ).is_file() else {}
    zh = json.loads((LOCALES / "error.zh-CN.json").read_text(encoding="utf-8")) if (
        LOCALES / "error.zh-CN.json"
    ).is_file() else {}
    if en and zh and set(en) != set(zh):
        problems.append("en/zh-CN key trees differ")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="extract error codes from docs/29")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true")
    group.add_argument("--emit", action="store_true")
    args = parser.parse_args(argv)

    try:
        codes = parse(DOC.read_text(encoding="utf-8"))
    except (OSError, ExtractError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if args.emit:
        emit(codes)
        return 0

    problems = check(codes)
    if problems:
        for p in problems:
            print(f"- {p}", file=sys.stderr)
        return 1
    print(f"OK: {len(codes)} error codes (en/zh-CN in sync)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
